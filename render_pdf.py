"""Renders an AsciiDoc file to PDF with asciidoctor-pdf in docker, including a dated cover.

Usage: python render_pdf.py <infile.adoc> <outfile.pdf>

- Theme: <infile>.yml next to the AsciiDoc file is used as pdf theme, if it exists.
- Cover: if cover.svg exists next to the AsciiDoc file, its placeholder {revdate} is replaced by
  the :revdate: attribute of the AsciiDoc file and the result is printed to cover.pdf with
  headless Microsoft Edge, so the fonts of the SVG get embedded. The theme references cover.pdf.
- Needs Docker (image asciidoctor/docker-asciidoctor, pulled on first use) and the Python
  package docker (pip install docker).
"""
import html
import re
import shutil
import subprocess
import sys
import tempfile
import uuid
from pathlib import Path

import docker
from docker.errors import DockerException

IMAGE = "asciidoctor/docker-asciidoctor"
CONTAINER_WORKDIR = "/documents"
COVER_TEMPLATE = "cover.svg"
COVER_PDF = "cover.pdf"
# Files generated by asciidoctor-diagram / asciidoctor-mathematical next to the source file.
GENERATED_GLOBS = ["diag-*.svg", "stem-*.svg"]
EDGE_CANDIDATES = [
    Path(r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe"),
    Path(r"C:\Program Files\Microsoft\Edge\Application\msedge.exe"),
]
COVER_PAGE = """<!DOCTYPE html>
<html><head><meta charset="utf-8">
<style>
  @page {{ size: 210mm 297mm; margin: 0; }}
  html, body {{ margin: 0; }}
  svg {{ display: block; width: 210mm; height: 297mm; }}
</style></head>
<body>{svg}</body></html>
"""


def read_revdate(adoc: Path) -> str:
    """Returns the value of the :revdate: attribute in the document header."""
    match = re.search(r"^:revdate:\s*(.+?)\s*$", adoc.read_text(encoding="utf-8"), re.MULTILINE)
    if not match:
        raise RuntimeError(f"{adoc} has no :revdate: attribute, the cover needs it.")
    return match.group(1)


def find_edge() -> Path:
    """Returns the path of msedge.exe."""
    edge = next((p for p in EDGE_CANDIDATES if p.exists()), None) or shutil.which("msedge")
    if not edge:
        raise RuntimeError("Microsoft Edge (msedge.exe) not found, it renders the cover.")
    return Path(edge)


def render_cover(template: Path, revdate: str, pdf: Path) -> None:
    """Prints the SVG template with the inserted date as a single A4 page."""
    svg = template.read_text(encoding="utf-8").replace("{revdate}", html.escape(revdate))
    with tempfile.TemporaryDirectory() as tmp:
        page = Path(tmp) / "cover.html"
        page.write_text(COVER_PAGE.format(svg=svg), encoding="utf-8")
        target = Path(tmp) / "cover.pdf"
        # An own profile directory keeps the headless instance apart from a running Edge.
        subprocess.run([str(find_edge()), "--headless", "--disable-gpu", "--no-first-run",
                        f"--user-data-dir={Path(tmp) / 'profile'}", "--no-pdf-header-footer",
                        f"--print-to-pdf={target}", page.as_uri()],
                       check=True, capture_output=True, timeout=120)
        if not target.exists() or target.stat().st_size == 0:
            raise RuntimeError("Edge did not create the cover PDF.")
        shutil.copyfile(target, pdf)


def render_pdf(adoc: Path, pdf: Path) -> str:
    """Runs asciidoctor-pdf in docker and returns its messages (warnings)."""
    workdir = adoc.parent
    # The container writes into the mounted folder, the result is moved to pdf afterwards.
    temp_name = f".render-{uuid.uuid4().hex}.pdf"
    command = ["asciidoctor-pdf", "-r", "asciidoctor-mathematical", "-r", "asciidoctor-diagram",
               "-a", "allow-uri-read", "-a", "stem", "-a", "mathematical-format=svg"]
    theme = adoc.with_suffix(".yml")
    if theme.exists():
        command += ["-a", f"pdf-theme={theme.name}", "-a", f"pdf-themesdir={CONTAINER_WORKDIR}"]
    command += ["-o", temp_name, adoc.name]
    try:
        # Detached run, because only then the warnings of asciidoctor-pdf can be read back.
        container = docker.from_env().containers.run(
            image=IMAGE, command=command, working_dir=CONTAINER_WORKDIR, detach=True,
            volumes={str(workdir): {"bind": CONTAINER_WORKDIR, "mode": "rw"}})
        try:
            exit_code = container.wait()["StatusCode"]
            output = container.logs(stdout=True, stderr=True).decode("utf-8", errors="replace")
        finally:
            container.remove(force=True)
    except DockerException as exc:
        raise RuntimeError(f"Docker is not available: {exc}") from exc
    finally:
        cleanup(workdir)
    result = workdir / temp_name
    if exit_code != 0 or not result.exists():
        result.unlink(missing_ok=True)
        raise RuntimeError(f"asciidoctor-pdf failed (exit code {exit_code}):\n{output}")
    shutil.move(result, pdf)
    return output


def cleanup(workdir: Path) -> None:
    """Removes the cache and the images that the asciidoctor extensions leave behind."""
    shutil.rmtree(workdir / ".asciidoctor", ignore_errors=True)
    for pattern in GENERATED_GLOBS:
        for path in workdir.glob(pattern):
            path.unlink()


def main() -> None:
    """Renders the cover (if there is a template) and then the PDF."""
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    adoc, pdf = Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve()
    if not adoc.is_file():
        sys.exit(f"[ERROR] AsciiDoc file not found: {adoc}")
    try:
        template = adoc.parent / COVER_TEMPLATE
        if template.exists():
            revdate = read_revdate(adoc)
            render_cover(template, revdate, adoc.parent / COVER_PDF)
            print(f"[INFO] {COVER_PDF} created, version {revdate}.")
        print(f"[INFO] Rendering {adoc.name} ...")
        sys.stdout.write(render_pdf(adoc, pdf))
    except (RuntimeError, subprocess.SubprocessError) as exc:
        sys.exit(f"[ERROR] {exc}")
    print(f"[INFO] {pdf} created.")


if __name__ == "__main__":
    main()
